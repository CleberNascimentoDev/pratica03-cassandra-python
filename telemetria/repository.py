"""Contrato da persistência. A interface não importa o driver Cassandra."""
from datetime import datetime
from typing import Protocol

from .models import Reading, ReadResult


class Repository(Protocol):
    mode: str

    def connect(self) -> None: ...
    def insert(self, reading: Reading) -> None: ...
    def read(self, sensor: str, start: datetime, end: datetime, *, role: str = 'monitor', limit: int = 500) -> ReadResult: ...
    def calibrate(self, sensor: str, when: datetime, value: float) -> None: ...
    def delete(self, sensor: str, when: datetime) -> None: ...
    def close(self) -> None: ...
